"""
COMPONENT : Retrieval - graph (Cypher)
PURPOSE   : Turn a question into parameterised Cypher queries over the
            knowledge graph: financial metrics (company, segment, product),
            risks, executives / board, competitors; side-by-side results when
            two companies are named.
INPUTS    : question text; a Neo4j driver (fin_graph_rag.graph_builder.driver_session)
OUTPUTS   : list[dict] graph facts, each with a one-line `text` and `sources`
            (report name + page) so answers can cite them
DEPENDS ON: neo4j driver; graph schema written by fin_graph_rag.graph_builder
PANEL NOTE: Detection is deliberately simple keyword matching (as pipeline.txt
            specifies) - transparent and testable. Exact figures come from the
            graph, so "What was Microsoft's FY2024 net income?" returns 88,136
            with its pages, and the pro forma 88,308 only when the question
            asks for pro forma figures. Unrecognised questions return [] and
            fall back to text retrieval; nothing is guessed.
"""

from __future__ import annotations

import re

# Names the question may use for each reporting company. "iPhone maker" is the
# only descriptive alias (a test case); other descriptions are not guessed.
COMPANY_ALIASES = {
    "apple": [r"\bapple\b", r"\baapl\b", r"\biphone maker\b"],
    "microsoft": [r"\bmicrosoft\b", r"\bmsft\b"],
    # IBM and NVIDIA (added 2026-10-29): legal name and ticker only.
    "ibm": [r"\bibm\b", r"\binternational business machines\b"],
    "nvidia": [r"\bnvidia\b", r"\bnvda\b"],
}
SHORT_NAMES = {"apple": "Apple", "microsoft": "Microsoft", "ibm": "IBM", "nvidia": "NVIDIA"}

# Order matters: more specific phrases first ("earnings per share" before "earnings").
METRIC_KEYWORDS = [
    ("diluted_eps", r"earnings per share|\beps\b"),
    ("operating_cash_flow", r"cash (?:from|generated by) operations|operating cash flow|cash flows? from operating|operations generate"),
    ("share_repurchases", r"repurchas|buy(?:ing)? ?back|buyback"),
    ("dividends_paid", r"dividend"),
    ("research_and_development", r"research and development|research, development|\br&d\b"),
    # NVIDIA says "sales, general and administrative"; removed once matched so
    # "sales" does not also select revenue (see detect_metrics).
    ("selling_general_and_administrative", r"(?:selling|sales), general(?: and administrative)?|\bsg&a\b"),
    ("sales_and_marketing", r"sales and marketing"),
    ("general_and_administrative", r"general and administrative"),
    # Before the tax provision: its phrase is removed once matched (see detect_metrics).
    ("income_before_taxes", r"income before (?:provision for )?income tax(?:es)?|pre-?tax income|before (?:income )?taxes"),
    ("provision_for_income_taxes", r"provision for income tax|income tax (?:provision|expense)"),
    ("total_assets", r"total assets|\bassets\b"),
    # IBM and NVIDIA report "gross profit" - the same measure (see entity_extractor).
    ("gross_margin", r"gross margin|gross profit"),
    ("operating_income", r"operating income|operating profit"),
    ("cash_and_cash_equivalents", r"cash and cash equivalents|cash holdings|cash on hand"),
    ("capital_expenditures", r"capital expenditure|\bcapex\b|property, plant and equipment|property and equipment"),
    # NVIDIA's capital-spending line also covers intangibles - a separate metric,
    # returned for the same words and labelled with its own name.
    ("purchases_of_property_equipment_and_intangibles",
     r"capital expenditure|\bcapex\b|property, plant and equipment|property and equipment"),
    ("depreciation_and_amortization", r"depreciation"),
    ("depreciation_amortization_and_other", r"depreciation"),
    ("share_based_compensation", r"(?:share|stock)-based compensation"),
    ("total_current_assets", r"current assets"),
    ("total_liabilities", r"\bliabilities\b"),
    ("shareholders_equity", r"(?:shareholders|stockholders)['’]? equity"),
    ("net_income", r"net income|\bprofit\b|\bearnings\b|\bearn\b"),
    ("revenue", r"revenue|net sales|\bsales\b|\bsell\b|\bsold\b|top line|generate"),
]
SEGMENTS = {
    "apple": ["Americas", "Europe", "Greater China", "Japan", "Rest of Asia Pacific"],
    "microsoft": ["Productivity and Business Processes", "Intelligent Cloud", "More Personal Computing"],
}
PRODUCTS = {"apple": ["iPhone", "Mac", "iPad", "Wearables, Home and Accessories", "Services"]}
RISK_WORDS = r"\brisks?\b|challenge|threat"
PERSON_WORDS = r"\bceo\b|\bcfo\b|chief|executive officer|executives?\b|leadership|\bboard\b|director"
COMPETITOR_WORDS = r"compet"
SEGMENT_WORDS = r"segment"
LATEST_YEAR = 2025          # newest fiscal year in the indexed reports


def detect_companies(q: str) -> list[str]:
    ql = q.lower()
    return [c for c, pats in COMPANY_ALIASES.items() if any(re.search(p, ql) for p in pats)]


def detect_years(q: str) -> list[int]:
    """Fiscal years mentioned: "fiscal 2024", "FY24", "FY2024", "2023"."""
    years = set()
    for m in re.finditer(r"\b(?:fy|fiscal(?: year)?)\s*'?(\d{2}|\d{4})\b|\b(20\d{2})\b", q, re.I):
        y = m.group(1) or m.group(2)
        years.add(int(y) + 2000 if len(y) == 2 else int(y))
    return sorted(years)


def detect_metrics(q: str) -> list[str]:
    ql = q.lower()
    found = []
    for metric, pattern in METRIC_KEYWORDS:
        if re.search(pattern, ql):
            found.append(metric)
            # "earnings per share" (and "gross profit") must not also mean net income; "income before
            # provision for income taxes" must not also mean the tax provision.
            if metric in ("diluted_eps", "income_before_taxes", "selling_general_and_administrative", "gross_margin"):
                ql = re.sub(pattern, " ", ql)
    return found


def detect_segments(q: str, company: str) -> list[str]:
    # Company aliases are removed first: "the iPhone maker" names Apple, not the iPhone product.
    ql = q.lower()
    for pat in COMPANY_ALIASES.get(company, []):
        ql = re.sub(pat, " ", ql)
    names = SEGMENTS.get(company, []) + PRODUCTS.get(company, [])
    hits = [n for n in names if re.search(r"\b" + re.escape(n.lower()), ql)]
    # "Microsoft Cloud" (a reported revenue figure) is not the Intelligent Cloud segment.
    return [h for h in hits if not (h == "Intelligent Cloud" and "intelligent" not in ql)]


def detect_basis(q: str) -> list[str]:
    ql = q.lower()
    bases = ["gaap"]
    if "pro forma" in ql or re.search(r"if the .* acquisition had", ql):
        bases = ["pro_forma"]
    if re.search(r"non-gaap|adjusted", ql):
        bases.append("non_gaap")
    return bases


def detect_intents(q: str) -> list[str]:
    ql = q.lower()
    intents = []
    if detect_metrics(q):
        intents.append("metric")
    if re.search(SEGMENT_WORDS, ql):
        intents.append("segment")
    if re.search(RISK_WORDS, ql):
        intents.append("risk")
    if re.search(PERSON_WORDS, ql):
        intents.append("person")
    if re.search(COMPETITOR_WORDS, ql):
        intents.append("competitor")
    return intents


def source_label(report_name: str, page: int) -> str:
    """"Apple 10-K FY2024" + 32 -> "Apple Annual Report FY2024, p.32"."""
    return f"{report_name.replace(' 10-K ', ' Annual Report ')}, p.{page}"


METRIC_QUERY = """
MATCH (c:Company {id: $company})-[:HAS_METRIC]->(m:FinancialMetric)
WHERE m.metric IN $metrics AND m.basis IN $bases
  AND (size($years) = 0 OR m.fiscal_year IN $years)
  AND CASE
        WHEN size($segments) > 0 THEN (m.segment IN $segments OR m.product IN $segments)
        WHEN $all_segments THEN m.segment IS NOT NULL
        ELSE m.segment IS NULL AND m.product IS NULL
      END
MATCH (m)-[e:REPORTED_IN]->(r:Report)
WITH c, m, e, r ORDER BY (r.year = m.fiscal_year) DESC, r.year DESC, e.page
RETURN c.name AS company_name, m.metric AS metric, m.fiscal_year AS fiscal_year, m.value AS value,
       m.unit AS unit, m.basis AS basis, m.segment AS segment, m.product AS product, m.conflict AS conflict,
       collect({report: r.name, year: r.year, page: e.page, value: e.value, chunk_id: e.chunk_id}) AS evidence
ORDER BY metric, segment, product, fiscal_year
"""
RISK_QUERY = """
MATCH (c:Company {id: $company})-[:FACES_RISK {fiscal_year: $year}]->(k:Risk)-[:IN_CATEGORY]->(cat:RiskCategory)
MATCH (k)-[d:DISCLOSED_IN]->(r:Report)
RETURN c.name AS company_name, cat.name AS category, k.title AS title, k.description AS description,
       r.name AS report, d.page AS page, d.chunk_id AS chunk_id
ORDER BY category, page
"""
PERSON_QUERY = """
MATCH (c:Company {id: $company})-[h:HAS_EXECUTIVE|BOARD_MEMBER {fiscal_year: $year}]->(p:Person)
WHERE ($role IS NULL OR toLower(h.role) CONTAINS $role) AND ($board OR type(h) = 'HAS_EXECUTIVE')
MATCH (c)-[:FILED]->(r:Report {year: $year})
RETURN c.name AS company_name, p.name AS name, h.role AS role, type(h) AS relation, r.name AS report,
       h.page AS page, h.chunk_id AS chunk_id
ORDER BY relation DESC, name
"""
COMPETITOR_QUERY = """
MATCH (c:Company {id: $company})-[w:COMPETES_WITH]->(o)
WHERE size($years) = 0 OR w.fiscal_year IN $years
MATCH (c)-[:FILED]->(r:Report {year: w.fiscal_year})
RETURN c.name AS company_name, o.name AS name, CASE WHEN o:Offering THEN "Offering" ELSE "Company" END AS kind, w.context AS context,
       w.fiscal_year AS fiscal_year, r.name AS report, w.page AS page, w.chunk_id AS chunk_id
ORDER BY fiscal_year DESC, name
"""


def _fmt_value(value: float, unit: str) -> str:
    if unit == "USD per share":
        return f"${value:,.2f} per share"
    sign = "-" if value < 0 else ""
    return f"{sign}${abs(value):,.0f} million"


def metric_text(r: dict) -> str:
    scope = r["segment"] or r["product"]
    basis = {"gaap": "GAAP", "non_gaap": "non-GAAP", "pro_forma": "unaudited pro forma"}[r["basis"]]
    what = r["metric"].replace("_", " ")
    text = (f"{r['company_name']}{' - ' + scope if scope else ''}: {what}, fiscal year {r['fiscal_year']}: "
            f"{_fmt_value(r['value'], r['unit'])} ({basis})")
    if r["conflict"]:
        others = sorted({(e["report"], e["value"]) for e in r["evidence"] if e["value"] != r["value"]})
        text += " [reports disagree: " + "; ".join(f"{rep} states {_fmt_value(v, r['unit'])}" for rep, v in others) + "]"
    return text


def cypher_search(driver, query: str, database=None, max_items: int = 40,
                  default_companies: list[str] | None = None) -> list[dict]:
    """Structured facts for `query`; [] if no company or intent is recognised."""
    # A question that names no company uses the caller's scope (e.g. the UI's
    # company selection); one that names a company always uses that company.
    companies = detect_companies(query) or list(default_companies or [])
    intents = detect_intents(query)
    if not companies or not intents:
        return []
    years = detect_years(query)
    run = lambda cypher, **p: [dict(r) for r in driver.execute_query(cypher, database_=database, **p).records]
    all_facts: list[dict] = []
    for company in companies:                    # two companies -> side-by-side ("compare") results
        facts: list[dict] = []
        if "metric" in intents or "segment" in intents:
            segments = detect_segments(query, company)
            metrics = detect_metrics(query) or ["revenue", "operating_income"]
            for r in run(METRIC_QUERY, company=company, metrics=metrics, bases=detect_basis(query), years=years,
                         segments=segments, all_segments="segment" in intents and not segments):
                facts.append({"type": "metric", "company": company, **r, "text": metric_text(r),
                              "sources": [source_label(e["report"], e["page"]) for e in r["evidence"][:3]]})
        year = max(years) if years else LATEST_YEAR
        if "risk" in intents:
            for r in run(RISK_QUERY, company=company, year=year):
                facts.append({"type": "risk", "company": company, "fiscal_year": year, **r,
                              "text": f"{r['company_name']} FY{year} risk ({r['category']}): {r['title']} - {r['description']}",
                              "sources": [source_label(r["report"], r["page"])]})
        if "person" in intents:
            ql = query.lower()
            role = ("chief executive" if re.search(r"\bceo\b|chief executive", ql) else
                    "chief financial" if re.search(r"\bcfo\b|chief financial", ql) else None)
            board = bool(re.search(r"\bboard\b|director", ql)) or role is None
            for r in run(PERSON_QUERY, company=company, year=year, role=role, board=board):
                kind = "board member" if r["relation"] == "BOARD_MEMBER" else "executive"
                facts.append({"type": "person", "company": company, "fiscal_year": year, **r,
                              "text": f"{r['company_name']} FY{year} {kind}: {r['name']} - {r['role']}",
                              "sources": [source_label(r["report"], r["page"])]})
        if "competitor" in intents:
            for r in run(COMPETITOR_QUERY, company=company, years=years):
                facts.append({"type": "competitor", "company": company, **r,
                              "text": f"{r['company_name']} FY{r['fiscal_year']} names {r['name']} "
                                      f"({r['kind'].lower()}) as a competitor in {r['context']}",
                              "sources": [source_label(r["report"], r["page"])]})
        all_facts.extend(facts[:max_items])      # cap per company so a comparison keeps both sides
    return all_facts
