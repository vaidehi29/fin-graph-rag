"""
COMPONENT : Entity and relation extraction
PURPOSE   : Turn the parsed 10-K tables into validated financial facts
            (company / segment / product metrics per fiscal year), each with
            the page, chunk and source row it came from.
INPUTS    : data/extracted/pages.jsonl (re-parsed with fin_graph_rag.preprocess
            so every table row keeps its PDF page), data/processed/chunks.jsonl
            (to link each table to the chunk that holds it)
OUTPUTS   : list[Fact] - one per (company, metric, segment/product, fiscal
            year, basis), carrying every piece of evidence for it; facts whose
            evidence disagrees are flagged `conflict`
DEPENDS ON: fin_graph_rag.preprocess (table detection, column years, qualifiers)
PANEL NOTE: Numbers come straight from the reports' own tables, not from an
            LLM, so a figure in the graph is exactly the figure on the cited
            page. Rules are deliberately strict: only allow-listed tables, only
            rows whose values line up one-to-one with the table's year
            columns, only tables with a stated "in millions" unit. Anything
            else is skipped and counted, never guessed.
"""

from __future__ import annotations

import json
import re
from collections import Counter, defaultdict
from dataclasses import asdict, dataclass, field
from pathlib import Path

from fin_graph_rag.preprocess import DocStats, clean_doc, is_row, to_units

PAGES_PATH = Path("data/extracted/pages.jsonl")
CHUNKS_PATH = Path("data/processed/chunks.jsonl")

COMPANY_NAMES = {"apple": "Apple Inc.", "microsoft": "Microsoft Corporation"}

# Tables we read facts from: primary statements and the MD&A summary/segment
# tables. PANEL: an allow-list keeps out look-alike rows such as Microsoft's
# Activision "net impact" table ("Revenue $ 5,729"), which is not total revenue.
# Statement titles are matched in CAPITALS only: the net-impact table's intro
# says "...on our consolidated income statements since...", which a
# case-insensitive match wrongly accepted.
STATEMENT_TITLES = re.compile(r"STATEMENTS OF OPERATIONS|INCOME STATEMENTS|BALANCE SHEETS|CASH FLOWS|"
                              r"SUMMARY RESULTS OF OPERATIONS|SEGMENT RESULTS OF OPERATIONS")
MDA_TITLES = re.compile(
    r"net sales by reportable segment|net sales by category|Segment revenue, cost of revenue|"
    r"reconciles our financial results|unaudited pro forma|"
    r"(?:^|/ )(?:Gross Margin|Operating Expenses|Research and Development|Sales and Marketing|"
    r"General and Administrative)\b", re.I)
# In these tables, rows must name a segment/product (or be an explicit total).
SEGMENT_TABLES = re.compile(r"SEGMENT RESULTS|by reportable segment|Segment revenue", re.I)


def table_allowed(title: str) -> bool:
    return bool(STATEMENT_TITLES.search(title) or MDA_TITLES.search(title))

# Canonical metric -> row labels (lower-case, footnote markers removed).
METRICS = {
    "revenue": ["total net sales", "total revenue", "revenue", "net sales"],
    "gross_margin": ["gross margin", "total gross margin"],
    "operating_income": ["operating income"],
    "net_income": ["net income"],
    "research_and_development": ["research and development"],
    "selling_general_and_administrative": ["selling, general and administrative"],
    "sales_and_marketing": ["sales and marketing"],
    "general_and_administrative": ["general and administrative"],
    "provision_for_income_taxes": ["provision for income taxes"],
    "diluted_eps": ["diluted", "diluted earnings per share"],
    "operating_cash_flow": ["cash generated by operating activities", "net cash from operations"],
    "share_repurchases": ["repurchases of common stock", "common stock repurchased"],
    "dividends_paid": ["payments for dividends and dividend equivalents", "common stock cash dividends paid"],
    "total_assets": ["total assets"],
}
# Non-GAAP rows in Microsoft's reconciliation tables.
NON_GAAP = {
    "adjusted gross margin (non-gaap)": "gross_margin",
    "adjusted operating income (non-gaap)": "operating_income",
    "adjusted net income (non-gaap)": "net_income",
    "adjusted diluted earnings per share (non-gaap)": "diluted_eps",
}
LABEL_TO_METRIC = {lab: m for m, labs in METRICS.items() for lab in labs}

# Sub-headers inside a table ("Net sales by reportable segment:", "Revenue",
# "Operating income") say which metric the segment/product rows below report.
# Some tables only say it in the title ("The following table shows net sales by
# reportable segment ..."), so the title is the fallback.
CONTEXT_PATTERNS = [(re.compile(r"^net sales\b|^revenue\b"), "revenue"),
                    (re.compile(r"^operating income\b"), "operating_income")]
TITLE_METRIC = [(re.compile(r"net sales by (reportable segment|category)", re.I), "revenue")]


def context_metric(context: str, title: str) -> str | None:
    for rx, metric in CONTEXT_PATTERNS:
        if rx.search(context):
            return metric
    if context.startswith(("cost of", "operating expenses", "gross margin")):
        return None                       # rows under these are not sales/income
    for rx, metric in TITLE_METRIC:
        if rx.search(title):
            return metric
    return None

SEGMENTS = {
    "apple": ["Americas", "Europe", "Greater China", "Japan", "Rest of Asia Pacific"],
    "microsoft": ["Productivity and Business Processes", "Intelligent Cloud", "More Personal Computing"],
}
PRODUCTS = {"apple": ["iPhone", "Mac", "iPad", "Wearables, Home and Accessories", "Services"]}

AMOUNT_RE = re.compile(r"^\(?-?\d(?:[\d,]*\d)?(?:\.\d+)?\)?$")
FOOTNOTE_RE = re.compile(r"\s*\(\d\)")


@dataclass
class Evidence:
    doc_id: str
    page: int
    chunk_id: str | None
    table_id: str
    table_title: str
    row_text: str
    value: float


@dataclass
class Fact:
    company: str
    metric: str
    fiscal_year: int
    basis: str                    # gaap | non_gaap | pro_forma
    unit: str                     # USD millions | USD per share
    value: float
    segment: str | None = None
    product: str | None = None
    conflict: bool = False
    evidence: list[Evidence] = field(default_factory=list)

    @property
    def key(self) -> str:
        return "|".join(str(x) for x in (self.company, self.metric, self.segment or "", self.product or "",
                                          self.fiscal_year, self.basis))


def parse_amounts(tokens: list[str]) -> list[float | None]:
    """Amounts from a row's value tokens, skipping percentages and markers.

    "(4) %", "22%", "1ppt" and "*" are change columns, not amounts;
    "(1,234)" is negative; "—" is an empty cell (kept as None for alignment).
    """
    out: list[float | None] = []
    for i, t in enumerate(tokens):
        nxt = tokens[i + 1] if i + 1 < len(tokens) else ""
        if t in ("$", "%", "*") or t.endswith("%") or t.endswith("ppt") or nxt == "%":
            continue
        if t in ("—", "–", "-"):
            out.append(None)
        elif AMOUNT_RE.match(t):
            neg = t.startswith("(")
            v = float(t.strip("()").replace(",", ""))
            out.append(-v if neg else v)
    return out


def split_row(text: str) -> tuple[str, list[str]]:
    """(label, value tokens): the label is everything before the first value token."""
    toks = text.split()
    for i, t in enumerate(toks):
        if t == "$" or AMOUNT_RE.match(t) or t in ("—", "–"):
            if i and not FOOTNOTE_RE.fullmatch(" " + t):
                return " ".join(toks[:i]), toks[i:]
    return text, []


def clean_label(label: str) -> str:
    return FOOTNOTE_RE.sub("", label).strip().rstrip(":").strip()


def table_facts(unit, doc: dict, chunk_of: dict[str, str], skipped: Counter) -> list[tuple[Fact, Evidence]]:
    """Facts from one table unit (a whole table or one labelled part)."""
    company = doc["company"]
    if not table_allowed(unit.title) or not unit.years:
        return []
    segment_table = bool(SEGMENT_TABLES.search(unit.title))
    if not re.search(r"in millions", unit.text, re.I):
        skipped["no_unit"] += 1
        return []
    pro_forma = re.search(r"pro forma", unit.title, re.I) is not None
    table_id = f"{doc['doc_id']}_t{unit.table_no:03d}"
    chunk_id = chunk_of.get(f"{table_id}#{unit.part}")
    segments = {s.lower(): s for s in SEGMENTS.get(company, [])}
    products = {p.lower(): p for p in PRODUCTS.get(company, [])}

    out = []
    context = ""                                  # last label-only line (sub-header)
    # Title lines are read too: a segment name can sit at the end of the title
    # ("SEGMENT RESULTS ... / Productivity and Business Processes").
    for i, line in enumerate(unit.lines):
        if i < unit.repeated and unit.part > 1:
            continue                              # header copied into a later part: already seen
        text = line.text
        if not is_row(text):
            context = clean_label(text).lower()
            continue
        label_raw, toks = split_row(text)
        label = clean_label(label_raw).lower()
        if not toks:
            continue

        metric = basis = segment = product = None
        basis = "pro_forma" if pro_forma else "gaap"
        if label in NON_GAAP:
            metric, basis = NON_GAAP[label], "non_gaap"
        elif label in LABEL_TO_METRIC:
            metric = LABEL_TO_METRIC[label]
            if context in segments:               # "Intelligent Cloud" / "Revenue $ ..."
                segment = segments[context]
        elif label in segments or label in products:
            metric = context_metric(context, unit.title)   # "Revenue" / "Intelligent Cloud $ ..."
            if metric is None:
                skipped["segment_row_without_metric_context"] += 1
                continue
            segment, product = segments.get(label), products.get(label)
        else:
            continue

        if segment_table and segment is None and product is None and not label.startswith("total"):
            skipped["company_level_row_in_segment_table"] += 1
            continue
        amounts = parse_amounts(toks)
        if metric == "diluted_eps":
            # "Diluted" also labels share counts ("Shares used in computing earnings
            # per share: / Diluted 15,812,547"); EPS rows sit under an "earnings per
            # share" sub-header (or say so in the label) and are small numbers.
            eps_context = "per share" in label or ("per share" in context and not context.startswith(("shares", "weighted")))
            if not eps_context or any(v is not None and abs(v) >= 1000 for v in amounts):
                continue
        if len(amounts) != len(unit.years):
            skipped["values_do_not_match_year_columns"] += 1
            continue
        unit_name = "USD per share" if metric == "diluted_eps" else "USD millions"
        for year, value in zip(unit.years, amounts):
            if value is None:
                continue
            fact = Fact(company, metric, year, basis, unit_name, value, segment, product)
            ev = Evidence(doc["doc_id"], line.page, chunk_id, table_id, unit.title[:200], text, value)
            out.append((fact, ev))
    return out


def merge_facts(pairs: list[tuple[Fact, Evidence]]) -> list[Fact]:
    """One Fact per key with all its evidence; disagreeing values -> conflict."""
    merged: dict[str, Fact] = {}
    for fact, ev in pairs:
        f = merged.setdefault(fact.key, fact)
        f.evidence.append(ev)
    for f in merged.values():
        values = {e.value for e in f.evidence}
        f.conflict = len(values) > 1
        # Prefer the value reported in that fiscal year's own report, else the most common.
        own = [e.value for e in f.evidence if e.doc_id.endswith(str(f.fiscal_year))]
        f.value = Counter(own or [e.value for e in f.evidence]).most_common(1)[0][0]
    return sorted(merged.values(), key=lambda f: f.key)


def extract_table_facts(pages_path: Path = PAGES_PATH, chunks_path: Path = CHUNKS_PATH) -> tuple[list[Fact], dict]:
    by_doc: dict[str, list[dict]] = defaultdict(list)
    for line in pages_path.read_text(encoding="utf-8").splitlines():
        p = json.loads(line)
        by_doc[p["doc_id"]].append(p)
    chunk_of: dict[str, str] = {}
    for line in chunks_path.read_text(encoding="utf-8").splitlines():
        c = json.loads(line)
        for t in c["tables"]:
            chunk_of[f'{t["table_id"]}#{t["part"]}'] = c["chunk_id"]

    pairs, skipped = [], Counter()
    for doc_id, pages in sorted(by_doc.items()):
        doc = {"doc_id": doc_id, "company": pages[0]["company"]}
        for unit in to_units(clean_doc(pages, DocStats(doc_id))):
            if unit.kind == "table" and not unit.lines[0].in_exhibits:
                pairs.extend(table_facts(unit, doc, chunk_of, skipped))
    facts = merge_facts(pairs)
    stats = {"rows_matched": len(pairs), "facts": len(facts),
             "conflicts": sum(f.conflict for f in facts), "skipped": dict(skipped)}
    return facts, stats


def fact_dict(f: Fact) -> dict:
    d = asdict(f)
    d["key"] = f.key
    return d


# ---------------------------------------------------------------------------
# Text entities (risks, executives, competitors) via Gemini - validated
# ---------------------------------------------------------------------------
# PANEL: The LLM proposes; the code verifies. Every item must cite the chunk it
# came from and copy a verbatim evidence quote from that chunk's own text;
# names must appear in that text; categories come from a fixed list. Items
# that fail are dropped and counted, never loaded.

RISK_CATEGORIES = ["macroeconomic", "competition", "supply_chain", "regulatory_legal", "cybersecurity_privacy",
                   "international_geopolitical", "intellectual_property", "product_technology",
                   "financial_tax", "people_operations", "artificial_intelligence", "other"]
# DEMO-KNOB: max chunk tokens sent per Gemini call (several chunks per call keeps
# the run to ~50 calls, inside one day's free quota).
BATCH_TOKENS = 3000
# Minimum evidence-quote length. Signature pages and executive tables are terse
# ("Al Gore Director"), and the person's name must also be in the chunk, so 2
# words suffice there; free-text risks need a longer verbatim span.
MIN_QUOTE_WORDS = {"risks": 4, "competitors": 3, "executives": 2}
COMPETITOR_KINDS = ["company", "product", "open_source_project"]
OWN_ALIASES = {"apple": "Apple Inc.", "apple inc": "Apple Inc.", "microsoft": "Microsoft Corporation",
               "microsoft corporation": "Microsoft Corporation", "microsoft corp": "Microsoft Corporation"}
LEGAL_SUFFIX = re.compile(r",?\s+(Inc\.?|Incorporated|Corporation|Corp\.?|LLC|Ltd\.?|plc|Co\.)$", re.I)

QUOTE_FIELD = {"type": "string", "description": "4-25 consecutive words copied verbatim from the cited passage"}


def _item_schema(props: dict) -> dict:
    props = {**props, "chunk_id": {"type": "string"}, "evidence_quote": QUOTE_FIELD}
    return {"type": "object", "properties": {"items": {"type": "array", "items": {
        "type": "object", "properties": props, "required": list(props)}}}, "required": ["items"]}


def _is_exec_chunk(c: dict) -> bool:
    listing = (c["section"] in ("Item 1", "Item 10") and re.search(r"executive officers", c["text"], re.I)
               and re.search(r"Chief|President", c["text"]))
    return bool(listing) or "/s/" in c["text"]        # signature page lists signing officers


TASKS = {
    "risks": {
        "select": lambda c: c["section"] == "Item 1A",
        "instruction": ("List each distinct risk factor the company discloses in these passages. "
                        f"category must be one of: {', '.join(RISK_CATEGORIES)}. title: a short name (max 12 words). "
                        "description: one sentence (max 40 words) restating only what the passage says."),
        "schema": _item_schema({"category": {"type": "string", "enum": RISK_CATEGORIES},
                                "title": {"type": "string"}, "description": {"type": "string"}}),
    },
    "executives": {
        "select": _is_exec_chunk,
        "instruction": ("List the people named as executive officers, or who sign the report as officers or "
                        "directors, with their role or title exactly as stated. Skip people only mentioned in passing."),
        "schema": _item_schema({"name": {"type": "string"}, "role": {"type": "string"}}),
    },
    "competitors": {
        "select": lambda c: c["section"] == "Item 1" and re.search(r"compet", c["text"], re.I) is not None,
        "instruction": ("List the competitors the report explicitly names: companies, competing products, or "
                        "open-source projects. Only names that appear in the passages; not the reporting company "
                        "itself, and not customers or partners. kind: company if the name is a company, product if "
                        "it is a product, open_source_project for open-source software such as Linux. "
                        "context: the area of competition (max 8 words)."),
        "schema": _item_schema({"name": {"type": "string"}, "kind": {"type": "string", "enum": COMPETITOR_KINDS},
                                "context": {"type": "string"}}),
    },
}
SYSTEM = ("You extract facts from SEC Form 10-K passages. Use only the passages given. Never add knowledge from "
          "outside them. If nothing qualifies, return an empty items list.")


@dataclass
class TextEntity:
    kind: str                      # risk | executive | competitor
    company: str
    fiscal_year: int
    doc_id: str
    chunk_id: str
    page: int
    quote: str
    fields: dict


_TYPO = str.maketrans({"’": "'", "‘": "'", "“": '"', "”": '"', "—": "-", "–": "-"})


def norm_text(s: str) -> str:
    return " ".join(s.translate(_TYPO).lower().split())


def own_text(c: dict) -> str:
    return c["text"][c.get("overlap_chars", 0):]


def batches(chunks: list[dict], max_tokens: int = BATCH_TOKENS) -> list[list[dict]]:
    """Consecutive chunks of one report, up to max_tokens per batch."""
    out: list[list[dict]] = []
    for c in chunks:
        if (out and out[-1][0]["doc_id"] == c["doc_id"]
                and sum(x["token_count"] for x in out[-1]) + c["token_count"] <= max_tokens):
            out[-1].append(c)
        else:
            out.append([c])
    return out


def build_prompt(task: str, batch: list[dict]) -> str:
    c0 = batch[0]
    head = (f"Report: {COMPANY_NAMES[c0['company']]} Form 10-K for fiscal year {c0['fiscal_year']}.\n"
            f"{TASKS[task]['instruction']}\nFor every item give the chunk_id of the passage it comes from and an "
            f"evidence_quote copied word for word from that passage.\n")
    body = "\n\n".join(f"[chunk_id: {c['chunk_id']}]\n{own_text(c)}" for c in batch)
    return f"{head}\n{body}"


def canonical_company(name: str) -> str:
    stripped = LEGAL_SUFFIX.sub("", name.strip())
    return OWN_ALIASES.get(stripped.lower(), stripped)


def validate(task: str, items: list[dict], batch: list[dict], rejected: Counter) -> list[TextEntity]:
    by_id = {c["chunk_id"]: c for c in batch}
    out = []
    for it in items:
        c = by_id.get(it.get("chunk_id", ""))
        if c is None:
            rejected[f"{task}:unknown_chunk"] += 1
            continue
        text = norm_text(own_text(c))
        quote = norm_text(it.get("evidence_quote", ""))
        if len(quote.split()) < MIN_QUOTE_WORDS[task] or quote not in text:
            rejected[f"{task}:quote_not_in_chunk"] += 1
            continue
        if task == "risks":
            if it.get("category") not in RISK_CATEGORIES or not it.get("title", "").strip():
                rejected[f"{task}:bad_category_or_title"] += 1
                continue
            fields = {"category": it["category"], "title": it["title"].strip()[:150],
                      "description": it.get("description", "").strip()[:400]}
        elif task == "executives":
            name = " ".join(it.get("name", "").split())
            if not name or norm_text(name).replace(".", "") not in text.replace(".", ""):
                rejected[f"{task}:name_not_in_chunk"] += 1
                continue
            fields = {"name": name.title() if name.isupper() else name, "role": it.get("role", "").strip()[:150]}
        else:
            raw = it.get("name", "").strip()
            name = canonical_company(raw)
            if not name or not name[0].isupper() or norm_text(LEGAL_SUFFIX.sub("", raw)) not in text:
                rejected[f"{task}:name_not_in_chunk"] += 1
                continue
            if name == COMPANY_NAMES[c["company"]]:
                rejected[f"{task}:self_reference"] += 1
                continue
            kind = it.get("kind") if it.get("kind") in COMPETITOR_KINDS else "company"
            fields = {"name": name, "kind": kind, "context": it.get("context", "").strip()[:100]}
        out.append(TextEntity({"risks": "risk", "executives": "executive", "competitors": "competitor"}[task],
                              c["company"], c["fiscal_year"], c["doc_id"], c["chunk_id"], c["page_start"],
                              it["evidence_quote"].strip(), fields))
    return out


def select_batches(chunks: list[dict], task: str) -> list[list[dict]]:
    chunks = [c for c in chunks if not c["in_exhibits"]]   # the report's own signature page precedes the exhibits
    return batches([c for c in chunks if TASKS[task]["select"](c)])


def extract_text_entities(llm, chunks_path: Path = CHUNKS_PATH, tasks=tuple(TASKS),
                          limit: int | None = None) -> tuple[list[TextEntity], dict]:
    chunks = [json.loads(l) for l in chunks_path.read_text(encoding="utf-8").splitlines() if l.strip()]
    entities, rejected, calls = [], Counter(), Counter()
    for task in tasks:
        for batch in select_batches(chunks, task)[:limit]:
            try:
                result = llm.generate(build_prompt(task, batch), TASKS[task]["schema"], SYSTEM)
            except json.JSONDecodeError:
                # FALLBACK: malformed model output (already logged by the client, not
                # cached) - skip this batch with no entities; the next run retries it.
                rejected[f"{task}:malformed_json_batch"] += 1
                continue
            calls[task] += 1
            entities.extend(validate(task, result.get("items", []), batch, rejected))
    # The same item can come back twice (repeated text): keep one per report.
    seen, unique = set(), []
    for e in entities:
        k = (e.kind, e.doc_id, norm_text(e.fields.get("title") or e.fields.get("name", "")))
        if k not in seen:
            seen.add(k)
            unique.append(e)
    stats = {"batches": dict(calls), "accepted": dict(Counter(e.kind for e in unique)),
             "duplicates_dropped": len(entities) - len(unique), "rejected": dict(rejected)}
    return unique, stats
